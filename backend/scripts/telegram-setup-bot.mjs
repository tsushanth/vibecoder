#!/usr/bin/env node
// Prints (default) or applies the bot's public setup: command list, description and short description in every language,
// and optionally the webhook. The texts come from lib/telegram/strings.js, so they never drift from the bot itself.
//
//   node scripts/telegram-setup-bot.mjs --markdown            > docs/telegram-botfather-commands.md
//   node scripts/telegram-setup-bot.mjs                       dry run: prints what would be sent, no network
//   TELEGRAM_BOT_TOKEN=... node scripts/telegram-setup-bot.mjs --apply
//   TELEGRAM_BOT_TOKEN=... TELEGRAM_WEBHOOK_SECRET=... node scripts/telegram-setup-bot.mjs --apply --webhook https://vibecoder-api.fly.dev
//
// The token is read from the environment only and is never printed.
import { STRINGS, LANGUAGES, NATIVE_NAMES } from '../lib/telegram/strings.js';

const COMMANDS = ['start', 'apps', 'language', 'link', 'stop', 'help'];
const clip = (s, n) => { const c = Array.from(s); return c.length <= n ? s : `${c.slice(0, n - 1).join('')}…`; };

export function commandsFor(lang) {
    const lines = STRINGS[lang].help.split('\n');
    return COMMANDS.map((c) => {
        const line = lines.find((l) => l.startsWith(`/${c} `));
        const desc = line ? line.replace(/^\/\w+\s*-\s*/, '') : c;
        return { command: c, description: clip(desc.charAt(0).toUpperCase() + desc.slice(1), 256) };
    });
}
export const descriptionFor = (lang) => clip(STRINGS[lang].about, 512);
export const shortDescriptionFor = (lang) => clip(STRINGS[lang].aboutShort, 120);

const args = process.argv.slice(2);
if (args.includes('--markdown')) {
    const out = ['# Telegram bot setup text, 26 languages + English', '',
        'Generated by `node backend/scripts/telegram-setup-bot.mjs --markdown` from `backend/lib/telegram/strings.js`. Machine-translated except where noted in docs/channels.md; needs native review.', '',
        'Apply everything at once with `TELEGRAM_BOT_TOKEN=... node backend/scripts/telegram-setup-bot.mjs --apply` (dry run without `--apply`), or paste by hand into BotFather:',
        '`/setcommands` takes the plain-text list (one `command - description` per line) and is per language through the API (`setMyCommands` with `language_code`); BotFather itself sets only the default (English) list, so use the script for the other languages.', ''];
    for (const l of LANGUAGES) {
        out.push(`## ${l} - ${NATIVE_NAMES[l]}${l === 'en' ? ' (default, no language_code)' : ''}`, '', '```', ...commandsFor(l).map((c) => `${c.command} - ${c.description}`), '```', '');
        out.push(`Description (max 512): ${descriptionFor(l)}`, '', `Short description (max 120): ${shortDescriptionFor(l)}`, '');
    }
    console.log(out.join('\n'));
    process.exit(0);
}

const apply = args.includes('--apply');
const whIdx = args.indexOf('--webhook');
const webhookBase = whIdx >= 0 ? args[whIdx + 1] : null;
const token = process.env.TELEGRAM_BOT_TOKEN;
if (apply && !token) { console.error('TELEGRAM_BOT_TOKEN is not set'); process.exit(1); }

async function call(method, params) {
    if (!apply) { console.log(`[dry run] ${method} ${JSON.stringify(params).slice(0, 200)}`); return; }
    const res = await fetch(`https://api.telegram.org/bot${token}/${method}`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(params) });
    const body = await res.json().catch(() => ({}));
    console.log(`${method}${params.language_code ? ` [${params.language_code}]` : ''}: ${body.ok ? 'ok' : `FAILED ${body.description || res.status}`}`);
    await new Promise((r) => setTimeout(r, 150));
}

for (const l of LANGUAGES) {
    const language_code = l === 'en' ? undefined : l;
    const extra = language_code ? { language_code } : {};
    await call('setMyCommands', { commands: commandsFor(l), ...extra });
    await call('setMyDescription', { description: descriptionFor(l), ...extra });
    await call('setMyShortDescription', { short_description: shortDescriptionFor(l), ...extra });
}
if (webhookBase) {
    const secret = process.env.TELEGRAM_WEBHOOK_SECRET;
    if (apply && !secret) { console.error('TELEGRAM_WEBHOOK_SECRET is not set'); process.exit(1); }
    await call('setWebhook', { url: `${webhookBase.replace(/\/$/, '')}/api/telegram/webhook/${secret || '<TELEGRAM_WEBHOOK_SECRET>'}`, secret_token: apply ? secret : '<TELEGRAM_WEBHOOK_SECRET>', allowed_updates: ['message', 'callback_query', 'my_chat_member'], drop_pending_updates: true, max_connections: 20 });
}
